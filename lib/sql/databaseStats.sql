SELECT
	(SELECT COUNT(*) FROM market) AS order_count,
	(SELECT COUNT(*) FROM market WHERE is_buy_order = 0) AS sell_orders,
	(SELECT COUNT(*) FROM market WHERE is_buy_order = 1) AS buy_orders,
	(SELECT COUNT(DISTINCT type_id) FROM market) AS tracked_types,
	(SELECT COUNT(DISTINCT system_id) FROM market) AS tracked_systems,
	(SELECT COUNT(DISTINCT type_id) FROM market WHERE system_id = 30000142 AND is_buy_order = 1) AS jita_buy_types,
	(SELECT COUNT(*) FROM marketListView) AS undercut_rows,
	(SELECT COUNT(*) FROM names) AS known_names,
	(SELECT COUNT(*) FROM systems) AS known_systems,
	(SELECT COUNT(*) FROM etags) AS etag_pages,
	(SELECT COUNT(*) FROM discord) AS alert_channels,
	(SELECT COUNT(*) FROM contracts) AS contract_count,
	(SELECT COUNT(*) FROM contract_items) AS contract_items_count,
	(SELECT COUNT(DISTINCT region_id) FROM contracts) AS contract_regions,
	(SELECT COUNT(*) FROM contracts WHERE items_fetched = 1) AS contracts_resolved,
	(SELECT COUNT(*) FROM contracts WHERE items_fetched = 0) AS contracts_pending,
	(SELECT COUNT(*) FROM contracts WHERE items_fetched = 0 AND items_attempts > 0) AS contracts_failed,
	(SELECT MAX(last_seen_round) FROM contracts) AS contract_last_seen_round,
	(SELECT COUNT(*) FROM market m LEFT JOIN names n ON n.id = m.location_id WHERE n.id IS NULL) AS unnamed_locations,
	(SELECT COUNT(*) FROM market m LEFT JOIN systems s ON s.system_id = m.system_id WHERE s.system_id IS NULL) AS unknown_systems,
	(SELECT MAX(updated_at) FROM market) AS last_write_at,
	(SELECT MIN(updated_at) FROM market) AS first_write_at,
	(SELECT version FROM schema_migrations ORDER BY version DESC LIMIT 1) AS schema_version,
	(SELECT * FROM pragma_page_count()) AS page_count,
	(SELECT * FROM pragma_page_size()) AS page_size,
	(SELECT * FROM pragma_journal_mode()) AS journal_mode
